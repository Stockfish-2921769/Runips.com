create or replace view public.professor_reviews_public
with (security_barrier = true)
as
select
  r.id,
  r.professor_id,
  r.overall_rating,
  r.pressure_rating,
  r.supervision_rating,
  r.communication_rating,
  r.autonomy_rating,
  r.lab_culture_rating,
  r.research_support_rating,
  r.career_support_rating,
  r.would_choose_again,
  r.student_level,
  r.relationship_status,
  r.communication_language,
  r.tags,
  r.comment,
  r.created_at,
  r.updated_at,
  count(*) filter (where v.value = 1)::integer as helpful_count,
  count(*) filter (where v.value = -1)::integer as unhelpful_count
from public.professor_reviews r
left join public.professor_review_votes v on v.review_id = r.id
where r.status = 'published'
group by r.id;

create or replace view public.professor_review_summaries
with (security_barrier = true)
as
select
  professor_id,
  count(*)::integer as review_count,
  round(avg(overall_rating)::numeric, 1) as overall_average,
  round(avg(pressure_rating)::numeric, 1) as pressure_average,
  round((100.0 * count(*) filter (where would_choose_again) / nullif(count(*), 0))::numeric, 0) as would_choose_again_percent,
  round(avg(supervision_rating)::numeric, 1) as supervision_average,
  round(avg(communication_rating)::numeric, 1) as communication_average,
  round(avg(autonomy_rating)::numeric, 1) as autonomy_average,
  round(avg(lab_culture_rating)::numeric, 1) as lab_culture_average,
  round(avg(research_support_rating)::numeric, 1) as research_support_average,
  round(avg(career_support_rating)::numeric, 1) as career_support_average
from public.professor_reviews
where status = 'published'
group by professor_id;

