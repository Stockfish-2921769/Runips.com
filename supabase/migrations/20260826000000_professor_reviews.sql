-- Professor/supervisor reviews for the self-hosted RunIPS backend.
-- Public views deliberately omit user_id so published reviews stay anonymous.

create table if not exists public.professor_reviews (
  id bigint generated by default as identity primary key,
  professor_id bigint not null references public.professors(id) on delete cascade,
  user_id uuid not null default auth.uid() references auth.users(id) on delete cascade,
  overall_rating smallint not null check (overall_rating between 1 and 5),
  pressure_rating smallint not null check (pressure_rating between 1 and 5),
  supervision_rating smallint not null check (supervision_rating between 1 and 5),
  communication_rating smallint not null check (communication_rating between 1 and 5),
  autonomy_rating smallint not null check (autonomy_rating between 1 and 5),
  lab_culture_rating smallint not null check (lab_culture_rating between 1 and 5),
  research_support_rating smallint not null check (research_support_rating between 1 and 5),
  career_support_rating smallint not null check (career_support_rating between 1 and 5),
  would_choose_again boolean not null,
  student_level text not null check (student_level in ('masters', 'doctoral', 'researchStudent', 'other')),
  relationship_status text not null check (relationship_status in ('current', 'former')),
  communication_language text not null check (communication_language in ('ja', 'en', 'zh', 'mixed', 'other')),
  tags text[] not null default '{}'::text[] check (cardinality(tags) <= 3),
  comment text not null check (char_length(comment) between 30 and 2000),
  status text not null default 'published' check (status in ('pending', 'published', 'rejected', 'hidden')),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  unique (professor_id, user_id)
);

create index if not exists professor_reviews_professor_created_idx
  on public.professor_reviews (professor_id, created_at desc)
  where status = 'published';

create table if not exists public.professor_review_votes (
  review_id bigint not null references public.professor_reviews(id) on delete cascade,
  user_id uuid not null default auth.uid() references auth.users(id) on delete cascade,
  value smallint not null check (value in (-1, 1)),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  primary key (review_id, user_id)
);

create table if not exists public.professor_review_reports (
  id bigint generated by default as identity primary key,
  review_id bigint not null references public.professor_reviews(id) on delete cascade,
  user_id uuid not null default auth.uid() references auth.users(id) on delete cascade,
  reason text not null check (char_length(reason) between 2 and 500),
  status text not null default 'open' check (status in ('open', 'resolved', 'dismissed')),
  created_at timestamptz not null default now(),
  unique (review_id, user_id)
);

create or replace function public.touch_professor_review_updated_at()
returns trigger
language plpgsql
set search_path = ''
as $$
begin
  new.updated_at = now();
  return new;
end;
$$;

drop trigger if exists professor_reviews_touch_updated_at on public.professor_reviews;
create trigger professor_reviews_touch_updated_at
before update on public.professor_reviews
for each row execute function public.touch_professor_review_updated_at();

drop trigger if exists professor_review_votes_touch_updated_at on public.professor_review_votes;
create trigger professor_review_votes_touch_updated_at
before update on public.professor_review_votes
for each row execute function public.touch_professor_review_updated_at();

