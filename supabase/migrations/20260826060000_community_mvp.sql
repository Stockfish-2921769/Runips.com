create table public.community_topics (
  id bigint generated by default as identity primary key,
  author_user_id uuid default auth.uid() references auth.users(id) on delete set null,
  kind text not null check (kind in ('question', 'discussion', 'guide')),
  category_id smallint not null references public.community_categories(id),
  title text not null check (
    char_length(btrim(title)) > 0
    and char_length(title) <= 160
  ),
  body text not null default '' check (char_length(body) <= 10000),
  status text not null default 'open' check (
    status in ('open', 'resolved', 'duplicate', 'closed', 'locked', 'hidden', 'deleted')
  ),
  accepted_reply_id bigint,
  duplicate_of_topic_id bigint references public.community_topics(id) on delete set null,
  source_type text not null default 'user' check (
    source_type in ('user', 'staff', 'wechat_archive')
  ),
  source_note text check (source_note is null or char_length(source_note) <= 500),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  last_activity_at timestamptz not null default now(),
  check (duplicate_of_topic_id is null or duplicate_of_topic_id <> id),
  check (
    (status = 'duplicate' and duplicate_of_topic_id is not null)
    or (status <> 'duplicate' and duplicate_of_topic_id is null)
  ),
  check (accepted_reply_id is null or kind = 'question')
);

create table public.community_replies (
  id bigint generated by default as identity primary key,
  topic_id bigint not null references public.community_topics(id) on delete cascade,
  author_user_id uuid default auth.uid() references auth.users(id) on delete set null,
  body text not null,
  quote_reply_id bigint references public.community_replies(id) on delete set null,
  status text not null default 'published' check (status in ('published', 'hidden', 'deleted')),
  source_type text not null default 'user' check (
    source_type in ('user', 'staff', 'wechat_archive')
  ),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  check (
    (status = 'deleted' and body = '')
    or (
      status <> 'deleted'
      and char_length(btrim(body)) > 0
      and char_length(body) <= 10000
    )
  )
);

