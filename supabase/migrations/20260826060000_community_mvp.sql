create or replace function public.resolve_community_report(
  p_report_id bigint,
  p_action text
)
returns text
language plpgsql
security definer
set search_path = ''
as $$
declare
  requesting_user uuid := auth.uid();
  normalised_action text := lower(btrim(coalesce(p_action, '')));
  target_topic_id bigint;
  target_reply_id bigint;
  next_report_status text;
begin
  if requesting_user is null or not public.viewer_is_community_moderator() then
    raise exception using errcode = '42501', message = 'Community moderator access required';
  end if;

  if normalised_action not in ('dismiss', 'resolve', 'hide') then
    raise exception using errcode = '22023', message = 'Invalid report action';
  end if;

  select report.topic_id, report.reply_id
  into target_topic_id, target_reply_id
  from public.community_reports report
  where report.id = p_report_id
  for update;

  if not found then
    raise exception using errcode = 'P0002', message = 'Community report was not found';
  end if;

  if normalised_action = 'hide' then
    if target_topic_id is not null then
      update public.community_topics
      set status = 'hidden',
          duplicate_of_topic_id = null,
          last_activity_at = now()
      where id = target_topic_id;
    else
      update public.community_topics topic
      set accepted_reply_id = null,
          status = case when topic.status = 'resolved' then 'open' else topic.status end,
          last_activity_at = now()
      where topic.accepted_reply_id = target_reply_id;

      update public.community_replies
      set status = 'hidden'
      where id = target_reply_id
        and status <> 'deleted';
    end if;

    next_report_status := 'resolved';
  elsif normalised_action = 'dismiss' then
    next_report_status := 'dismissed';
  else
    next_report_status := 'resolved';
  end if;

  update public.community_reports
  set status = next_report_status
  where id = p_report_id;

  return next_report_status;
end;
$$;

