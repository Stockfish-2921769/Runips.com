-- Extend the existing single-transaction erasure path. Community rows are
-- retained only as content-free tombstones where IDs are needed for thread
-- structure; no authored title, body, identity, or notification snapshot remains.
create or replace function public.delete_my_account(p_confirmation text)
returns void
language plpgsql
security definer
set search_path = ''
as $$
declare
  requesting_user uuid := auth.uid();
begin
  if requesting_user is null then
    raise exception using errcode = '42501', message = 'Authentication required';
  end if;

  if p_confirmation is distinct from 'DELETE MY ACCOUNT' then
    raise exception using errcode = '22023', message = 'Confirmation text does not match';
  end if;

  -- Serialise against Community topic/reply/report creation by this account so
  -- no authored content can appear after the scrub phase has passed.
  perform pg_catalog.pg_advisory_xact_lock(pg_catalog.hashtext(requesting_user::text));

  delete from public.feedback_submissions
  where user_id = requesting_user;

  -- Remove notifications owned by the account and notifications pointing to
  -- content authored by it before that content is scrubbed.
  delete from public.community_notifications notification
  where notification.recipient_user_id = requesting_user
     or notification.actor_user_id = requesting_user
     or exists (
       select 1
       from public.community_topics topic
       where topic.id = notification.topic_id
         and topic.author_user_id = requesting_user
     )
     or exists (
       select 1
       from public.community_replies reply
       where reply.id = notification.reply_id
         and reply.author_user_id = requesting_user
     );

  delete from public.community_reports report
  where report.reporter_user_id = requesting_user
     or exists (
       select 1
       from public.community_topics topic
       where topic.id = report.topic_id
         and topic.author_user_id = requesting_user
     )
     or exists (
       select 1
       from public.community_replies reply
       where reply.id = report.reply_id
         and reply.author_user_id = requesting_user
     );

  delete from public.community_subscriptions subscription
  where subscription.user_id = requesting_user
     or exists (
       select 1
       from public.community_topics topic
       where topic.id = subscription.topic_id
         and topic.author_user_id = requesting_user
     );

  delete from public.community_topic_tags topic_tag
  where exists (
    select 1
    from public.community_topics topic
    where topic.id = topic_tag.topic_id
      and topic.author_user_id = requesting_user
  );

  delete from public.community_topic_entity_links link
  where exists (
    select 1
    from public.community_topics topic
    where topic.id = link.topic_id
      and topic.author_user_id = requesting_user
  );

  -- A deleted reply cannot remain an accepted solution on somebody else's
  -- question. Return such questions to open before scrubbing the reply.
  update public.community_topics topic
  set accepted_reply_id = null,
      status = case when topic.status = 'resolved' then 'open' else topic.status end,
      last_activity_at = now()
  where exists (
    select 1
    from public.community_replies reply
    where reply.id = topic.accepted_reply_id
      and reply.author_user_id = requesting_user
  );

  -- If a canonical topic disappears, reopen its duplicates rather than leave
  -- them pointing at a content-free tombstone.
  update public.community_topics topic
  set duplicate_of_topic_id = null,
      status = case when topic.accepted_reply_id is null then 'open' else 'resolved' end,
      last_activity_at = now()
  where exists (
    select 1
    from public.community_topics deleted_topic
    where deleted_topic.id = topic.duplicate_of_topic_id
      and deleted_topic.author_user_id = requesting_user
  );

  update public.community_replies
  set author_user_id = null,
      body = '',
      quote_reply_id = null,
      status = 'deleted',
      source_type = 'user'
  where author_user_id = requesting_user;

  update public.community_topics
  set author_user_id = null,
      title = 'Deleted topic',
      body = '',
      status = 'deleted',
      accepted_reply_id = null,
      duplicate_of_topic_id = null,
      source_type = 'user',
      source_note = null,
      last_activity_at = now()
  where author_user_id = requesting_user;

  delete from public.community_moderators
  where user_id = requesting_user;

  update public.community_moderators
  set created_by = null
  where created_by = requesting_user;

  delete from auth.audit_log_entries
  where payload ->> 'actor_id' = requesting_user::text;

  delete from auth.users
  where id = requesting_user;

  if not found then
    raise exception using errcode = 'P0002', message = 'Account was not found';
  end if;
end;
$$;

