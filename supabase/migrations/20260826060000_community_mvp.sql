create or replace function public.create_community_topic(
  p_kind text,
  p_title text,
  p_body text,
  p_category_slug text
)
returns bigint
language plpgsql
security definer
set search_path = ''
as $$
declare
  requesting_user uuid := auth.uid();
  normalised_kind text := lower(btrim(coalesce(p_kind, '')));
  normalised_title text := btrim(coalesce(p_title, ''));
  normalised_body text := btrim(coalesce(p_body, ''));
  normalised_category_slug text := lower(btrim(coalesce(p_category_slug, '')));
  selected_category_id smallint;
  new_topic_id bigint;
begin
  if requesting_user is null then
    raise exception using errcode = '42501', message = 'Authentication required';
  end if;

  perform pg_catalog.pg_advisory_xact_lock(pg_catalog.hashtext(requesting_user::text));

  if normalised_kind not in ('question', 'discussion')
    and not (
      normalised_kind = 'guide'
      and public.viewer_is_community_moderator()
    ) then
    raise exception using errcode = '22023', message = 'Invalid community topic type';
  end if;

  if char_length(normalised_title) = 0 or char_length(normalised_title) > 160 then
    raise exception using errcode = '22023', message = 'Title must contain 1 to 160 characters';
  end if;

  if char_length(normalised_body) > 10000 then
    raise exception using errcode = '22023', message = 'Body must contain no more than 10000 characters';
  end if;

  select category.id
  into selected_category_id
  from public.community_categories category
  where category.slug = normalised_category_slug
    and category.is_active;

  if selected_category_id is null then
    raise exception using errcode = '22023', message = 'Invalid community category';
  end if;

  if (
    select count(*)
    from public.community_topics topic
    where topic.author_user_id = requesting_user
      and topic.created_at >= now() - interval '1 hour'
  ) >= 3 then
    raise exception using errcode = '54000', message = 'Topic creation rate limit reached';
  end if;

  if (
    select count(*)
    from public.community_topics topic
    where topic.author_user_id = requesting_user
      and topic.created_at >= now() - interval '24 hours'
  ) >= 10 then
    raise exception using errcode = '54000', message = 'Daily topic creation rate limit reached';
  end if;

  insert into public.community_topics (
    author_user_id,
    kind,
    category_id,
    title,
    body,
    source_type
  ) values (
    requesting_user,
    normalised_kind,
    selected_category_id,
    normalised_title,
    normalised_body,
    case when normalised_kind = 'guide' then 'staff' else 'user' end
  )
  returning id into new_topic_id;

  insert into public.community_subscriptions (topic_id, user_id)
  values (new_topic_id, requesting_user)
  on conflict do nothing;

  return new_topic_id;
end;
$$;

create or replace function public.create_community_reply(
  p_topic_id bigint,
  p_body text
)
returns bigint
language plpgsql
security definer
set search_path = ''
as $$
declare
  requesting_user uuid := auth.uid();
  normalised_body text := btrim(coalesce(p_body, ''));
  new_reply_id bigint;
begin
  if requesting_user is null then
    raise exception using errcode = '42501', message = 'Authentication required';
  end if;

  perform pg_catalog.pg_advisory_xact_lock(pg_catalog.hashtext(requesting_user::text));

  if char_length(normalised_body) = 0 or char_length(normalised_body) > 10000 then
    raise exception using errcode = '22023', message = 'Reply must contain 1 to 10000 characters';
  end if;

  if not exists (
    select 1
    from public.community_topics topic
    where topic.id = p_topic_id
      and topic.status in ('open', 'resolved')
  ) then
    raise exception using errcode = '22023', message = 'Topic is unavailable for replies';
  end if;

  if (
    select count(*)
    from public.community_replies reply
    where reply.author_user_id = requesting_user
      and reply.created_at >= now() - interval '1 hour'
  ) >= 20 then
    raise exception using errcode = '54000', message = 'Reply rate limit reached';
  end if;

  if (
    select count(*)
    from public.community_replies reply
    where reply.author_user_id = requesting_user
      and reply.created_at >= now() - interval '24 hours'
  ) >= 60 then
    raise exception using errcode = '54000', message = 'Daily reply rate limit reached';
  end if;

  insert into public.community_subscriptions (topic_id, user_id)
  values (p_topic_id, requesting_user)
  on conflict do nothing;

  insert into public.community_replies (
    topic_id,
    author_user_id,
    body,
    source_type
  ) values (
    p_topic_id,
    requesting_user,
    normalised_body,
    'user'
  )
  returning id into new_reply_id;

  update public.community_topics
  set last_activity_at = now()
  where id = p_topic_id;

  insert into public.community_notifications (
    recipient_user_id,
    actor_user_id,
    event_type,
    topic_id,
    reply_id
  )
  select
    subscription.user_id,
    requesting_user,
    'reply',
    p_topic_id,
    new_reply_id
  from public.community_subscriptions subscription
  where subscription.topic_id = p_topic_id
    and subscription.user_id <> requesting_user;

  return new_reply_id;
end;
$$;

create or replace function public.suggest_community_topics(
  p_query text,
  p_limit integer default 5
)
returns table (
  id bigint,
  kind text,
  title text,
  status text,
  category_slug text,
  category_name_en text,
  category_name_zh text,
  body_excerpt text,
  reply_count integer,
  accepted_reply_id bigint,
  duplicate_of_topic_id bigint,
  duplicate_of_title text,
  similarity_score real,
  last_activity_at timestamptz
)
language plpgsql
stable
security definer
set search_path = ''
as $$
declare
  normalised_query text := btrim(coalesce(p_query, ''));
  result_limit integer := greatest(1, least(coalesce(p_limit, 5), 50));
begin
  if char_length(normalised_query) = 0 or char_length(normalised_query) > 160 then
    return;
  end if;

  return query
  select
    topic.id,
    topic.kind,
    topic.title,
    topic.status,
    category.slug,
    category.name_en,
    category.name_zh,
    left(topic.body, 240),
    (
      select count(*)::integer
      from public.community_replies reply
      where reply.topic_id = topic.id
        and reply.status in ('published', 'deleted')
    ),
    topic.accepted_reply_id,
    topic.duplicate_of_topic_id,
    case
      when duplicate_target.status = 'hidden' then null
      else duplicate_target.title
    end,
    least(
      1.0,
      0.70 * search_match.title_similarity
      + case when lower(topic.title) = lower(normalised_query) then 0.30 else 0 end
      + case when search_match.body_match then 0.15 else 0 end
      + case when search_match.tag_exact_match then 0.25 else 0 end
      + case when search_match.tag_partial_match then 0.10 else 0 end
    )::real,
    topic.last_activity_at
  from public.community_topics topic
  join public.community_categories category on category.id = topic.category_id
  left join public.community_topics duplicate_target on duplicate_target.id = topic.duplicate_of_topic_id
  cross join lateral (
    select
      extensions.similarity(lower(topic.title), lower(normalised_query)) as title_similarity,
      position(lower(normalised_query) in lower(topic.body)) > 0 as body_match,
      exists (
        select 1
        from public.community_topic_tags topic_tag
        join public.community_tags tag on tag.id = topic_tag.tag_id
        where topic_tag.topic_id = topic.id
          and (
            lower(tag.slug) = lower(normalised_query)
            or lower(tag.name) = lower(normalised_query)
          )
      ) as tag_exact_match,
      exists (
        select 1
        from public.community_topic_tags topic_tag
        join public.community_tags tag on tag.id = topic_tag.tag_id
        where topic_tag.topic_id = topic.id
          and (
            position(lower(normalised_query) in lower(tag.slug)) > 0
            or position(lower(normalised_query) in lower(tag.name)) > 0
          )
      ) as tag_partial_match
  ) search_match
  where topic.status not in ('hidden', 'deleted')
    and (
      search_match.title_similarity >= 0.12
      or position(lower(normalised_query) in lower(topic.title)) > 0
      or position(lower(topic.title) in lower(normalised_query)) > 0
      or search_match.body_match
      or search_match.tag_partial_match
    )
  order by
    (lower(topic.title) = lower(normalised_query)) desc,
    least(
      1.0,
      0.70 * search_match.title_similarity
      + case when lower(topic.title) = lower(normalised_query) then 0.30 else 0 end
      + case when search_match.body_match then 0.15 else 0 end
      + case when search_match.tag_exact_match then 0.25 else 0 end
      + case when search_match.tag_partial_match then 0.10 else 0 end
    ) desc,
    (topic.status <> 'duplicate') desc,
    (topic.status = 'resolved') desc,
    topic.last_activity_at desc
  limit result_limit;
end;
$$;

create or replace function public.mark_community_solution(
  p_topic_id bigint,
  p_reply_id bigint
)
returns bigint
language plpgsql
security definer
set search_path = ''
as $$
declare
  requesting_user uuid := auth.uid();
  topic_author uuid;
  topic_kind text;
  topic_status text;
  reply_author uuid;
begin
  if requesting_user is null then
    raise exception using errcode = '42501', message = 'Authentication required';
  end if;

  select topic.author_user_id, topic.kind, topic.status
  into topic_author, topic_kind, topic_status
  from public.community_topics topic
  where topic.id = p_topic_id
  for update;

  if not found then
    raise exception using errcode = 'P0002', message = 'Community topic was not found';
  end if;

  if requesting_user is distinct from topic_author
    and not public.viewer_is_community_moderator() then
    raise exception using errcode = '42501', message = 'Only the topic author or a moderator can choose a solution';
  end if;

  if topic_kind <> 'question' or topic_status not in ('open', 'resolved') then
    raise exception using errcode = '22023', message = 'This topic cannot accept a solution';
  end if;

  if p_reply_id is null then
    update public.community_topics
    set accepted_reply_id = null,
        status = 'open',
        last_activity_at = now()
    where id = p_topic_id;

    return null;
  end if;

  select reply.author_user_id
  into reply_author
  from public.community_replies reply
  where reply.id = p_reply_id
    and reply.topic_id = p_topic_id
    and reply.status = 'published';

  if not found then
    raise exception using errcode = '22023', message = 'Solution must be a published reply on this topic';
  end if;

  update public.community_topics
  set accepted_reply_id = p_reply_id,
      status = 'resolved',
      last_activity_at = now()
  where id = p_topic_id;

  if reply_author is not null and reply_author <> requesting_user then
    insert into public.community_notifications (
      recipient_user_id,
      actor_user_id,
      event_type,
      topic_id,
      reply_id
    ) values (
      reply_author,
      requesting_user,
      'solution',
      p_topic_id,
      p_reply_id
    );
  end if;

  return p_reply_id;
end;
$$;

create or replace function public.report_community_content(
  p_target_type text,
  p_target_id bigint,
  p_reason text
)
returns bigint
language plpgsql
security definer
set search_path = ''
as $$
declare
  requesting_user uuid := auth.uid();
  normalised_target_type text := lower(btrim(coalesce(p_target_type, '')));
  normalised_reason text := btrim(coalesce(p_reason, ''));
  report_id bigint;
begin
  if requesting_user is null then
    raise exception using errcode = '42501', message = 'Authentication required';
  end if;

  perform pg_catalog.pg_advisory_xact_lock(pg_catalog.hashtext(requesting_user::text));

  if normalised_target_type not in ('topic', 'reply') then
    raise exception using errcode = '22023', message = 'Invalid report target';
  end if;

  if char_length(normalised_reason) < 2 or char_length(normalised_reason) > 1000 then
    raise exception using errcode = '22023', message = 'Report reason must contain 2 to 1000 characters';
  end if;

  if (
    select count(*)
    from public.community_reports report
    where report.reporter_user_id = requesting_user
      and report.created_at >= now() - interval '1 hour'
  ) >= 10 then
    raise exception using errcode = '54000', message = 'Report rate limit reached';
  end if;

  if normalised_target_type = 'topic' then
    if not exists (
      select 1
      from public.community_topics topic
      where topic.id = p_target_id
        and topic.status not in ('hidden', 'deleted')
    ) then
      raise exception using errcode = 'P0002', message = 'Report target was not found';
    end if;

    insert into public.community_reports (
      reporter_user_id,
      topic_id,
      reason
    ) values (
      requesting_user,
      p_target_id,
      normalised_reason
    )
    on conflict (reporter_user_id, topic_id) where topic_id is not null
    do update set
      reason = excluded.reason,
      status = 'open',
      updated_at = now()
    returning id into report_id;
  else
    if not exists (
      select 1
      from public.community_replies reply
      join public.community_topics topic on topic.id = reply.topic_id
      where reply.id = p_target_id
        and reply.status = 'published'
        and topic.status <> 'hidden'
    ) then
      raise exception using errcode = 'P0002', message = 'Report target was not found';
    end if;

    insert into public.community_reports (
      reporter_user_id,
      reply_id,
      reason
    ) values (
      requesting_user,
      p_target_id,
      normalised_reason
    )
    on conflict (reporter_user_id, reply_id) where reply_id is not null
    do update set
      reason = excluded.reason,
      status = 'open',
      updated_at = now()
    returning id into report_id;
  end if;

  return report_id;
end;
$$;

