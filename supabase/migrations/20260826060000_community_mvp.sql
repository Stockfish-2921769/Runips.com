create or replace function public.moderate_community_topic(
  p_topic_id bigint,
  p_action text,
  p_duplicate_of_topic_id bigint default null
)
returns text
language plpgsql
security definer
set search_path = ''
as $$
declare
  requesting_user uuid := auth.uid();
  normalised_action text := lower(btrim(coalesce(p_action, '')));
  topic_author uuid;
  next_status text;
begin
  if requesting_user is null or not public.viewer_is_community_moderator() then
    raise exception using errcode = '42501', message = 'Community moderator access required';
  end if;

  select topic.author_user_id
  into topic_author
  from public.community_topics topic
  where topic.id = p_topic_id
  for update;

  if not found then
    raise exception using errcode = 'P0002', message = 'Community topic was not found';
  end if;

  if normalised_action = 'duplicate' then
    if p_duplicate_of_topic_id is null or p_duplicate_of_topic_id = p_topic_id then
      raise exception using errcode = '22023', message = 'A distinct duplicate target is required';
    end if;

    update public.community_topics
    set status = 'duplicate',
        duplicate_of_topic_id = p_duplicate_of_topic_id,
        accepted_reply_id = null,
        last_activity_at = now()
    where id = p_topic_id;
  elsif normalised_action = 'lock' then
    update public.community_topics
    set status = 'locked',
        duplicate_of_topic_id = null,
        last_activity_at = now()
    where id = p_topic_id;
  elsif normalised_action in ('unlock', 'reopen', 'unhide') then
    update public.community_topics
    set status = case when accepted_reply_id is null then 'open' else 'resolved' end,
        duplicate_of_topic_id = null,
        last_activity_at = now()
    where id = p_topic_id;
  elsif normalised_action = 'close' then
    update public.community_topics
    set status = 'closed',
        duplicate_of_topic_id = null,
        last_activity_at = now()
    where id = p_topic_id;
  elsif normalised_action = 'hide' then
    update public.community_topics
    set status = 'hidden',
        duplicate_of_topic_id = null,
        last_activity_at = now()
    where id = p_topic_id;
  else
    raise exception using errcode = '22023', message = 'Invalid moderation action';
  end if;

  select topic.status
  into next_status
  from public.community_topics topic
  where topic.id = p_topic_id;

  if topic_author is not null and topic_author <> requesting_user then
    insert into public.community_notifications (
      recipient_user_id,
      actor_user_id,
      event_type,
      topic_id
    ) values (
      topic_author,
      requesting_user,
      'topic_moderated',
      p_topic_id
    );
  end if;

  return next_status;
end;
$$;

