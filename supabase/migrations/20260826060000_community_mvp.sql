create or replace function public.validate_community_topic_references()
returns trigger
language plpgsql
set search_path = ''
as $$
begin
  -- Keep status coherent when an FK action removes a canonical topic or an
  -- accepted reply. Explicit moderation updates already set both columns.
  if tg_op = 'UPDATE' then
    if old.duplicate_of_topic_id is not null
      and new.duplicate_of_topic_id is null
      and new.status = 'duplicate' then
      new.status := 'open';
    end if;

    if old.accepted_reply_id is not null
      and new.accepted_reply_id is null
      and new.status = 'resolved' then
      new.status := 'open';
    end if;
  end if;

  if new.accepted_reply_id is not null and not exists (
    select 1
    from public.community_replies r
    where r.id = new.accepted_reply_id
      and r.topic_id = new.id
      and r.status = 'published'
  ) then
    raise exception using errcode = '23514', message = 'Accepted reply must be a published reply on this topic';
  end if;

  if new.duplicate_of_topic_id is not null and not exists (
    select 1
    from public.community_topics target
    where target.id = new.duplicate_of_topic_id
      and target.status not in ('hidden', 'deleted', 'duplicate')
  ) then
    raise exception using errcode = '23514', message = 'Duplicate target must be an available canonical topic';
  end if;

  return new;
end;
$$;

create or replace function public.validate_community_reply_quote()
returns trigger
language plpgsql
set search_path = ''
as $$
begin
  if new.quote_reply_id is not null and not exists (
    select 1
    from public.community_replies quoted
    where quoted.id = new.quote_reply_id
      and quoted.topic_id = new.topic_id
      and quoted.status <> 'hidden'
  ) then
    raise exception using errcode = '23514', message = 'Quoted reply must belong to the same topic';
  end if;

  return new;
end;
$$;

